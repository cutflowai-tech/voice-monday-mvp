#!/usr/bin/env bash
# Route one extension (default 778) to the hosted ElevenLabs voice agent.
#
#   sudo scripts/pbx-elevenlabs-route.sh apply    # backup + additive changes + reload + verify
#   sudo scripts/pbx-elevenlabs-route.sh revert   # remove exactly those changes + reload
#   sudo scripts/pbx-elevenlabs-route.sh verify
#
# AGENT_PBX_MODE=audiosocket (default): Answer + AudioSocket to the local el-bridge
#   (127.0.0.1:9019), which talks to the agent over an outbound WebSocket. Works behind any
#   NAT or multi-line load balancer; no SIP trunk is configured.
# AGENT_PBX_MODE=sip: SIP/TLS trunk to sip.rtc.elevenlabs.io. Needs inbound UDP RTP, i.e. one
#   stable public IP with UDP 10000-10100 forwarded to the PBX.
#
# Reads from .env: AGENT_PBX_MODE, AGENT_PBX_EXTENSION (778), EL_BRIDGE_PORT (9019) and, for
# sip mode, ELEVENLABS_SIP_USERNAME/PASSWORD/NUMBER, PBX_PUBLIC_IP, PBX_LAN_IP, PBX_LOCAL_NET.
#
# What "apply" adds (nothing else is touched):
#   new  /etc/asterisk/extensions_voice_monday_el.conf  [voice-monday-el] with the extension
#   extensions.conf  + `[office-internal](+)` / `include => voice-monday-el` / `#include ...`
#   sip mode only:
#   new  /etc/asterisk/pjsip_voice_monday_el.conf       TLS transport + "elevenlabs" trunk
#   new  /etc/asterisk/keys/voice-monday-el.{crt,key}   self-signed cert for the TLS transport
#   pjsip.conf       + `#include pjsip_voice_monday_el.conf`
# Each appended block sits between `; >>> voice-monday-el` and `; <<< voice-monday-el`.
set -euo pipefail

ETC=/etc/asterisk
HERE="$(cd "$(dirname "$0")/.." && pwd)"
BEGIN="; >>> voice-monday-el (added by scripts/pbx-elevenlabs-route.sh; revert removes this block)"
END="; <<< voice-monday-el"
PJSIP_FILE="$ETC/pjsip_voice_monday_el.conf"
EXT_FILE="$ETC/extensions_voice_monday_el.conf"
KEYS="$ETC/keys"
CONTEXT="${PHONE_CONTEXT:-office-internal}"

[[ $EUID -eq 0 ]] || { echo "run with sudo" >&2; exit 1; }
ast() { asterisk -rx "$1"; }
end_nl() { [[ -z "$(tail -c1 "$1")" ]] || echo >>"$1"; }
env_get() { grep -E "^$1=" "$HERE/.env" 2>/dev/null | tail -1 | cut -d= -f2- || true; }
drop_block() { sed -i "\\|^; >>> voice-monday-el|,\\|^; <<< voice-monday-el|d" "$1"; }

MODE="$(env_get AGENT_PBX_MODE)"; MODE="${MODE:-audiosocket}"
EXT="$(env_get AGENT_PBX_EXTENSION)"; EXT="${EXT:-778}"
BRIDGE_PORT="$(env_get EL_BRIDGE_PORT)"; BRIDGE_PORT="${BRIDGE_PORT:-9019}"
SIP_USER="$(env_get ELEVENLABS_SIP_USERNAME)"
SIP_PASS="$(env_get ELEVENLABS_SIP_PASSWORD)"
SIP_NUMBER="$(env_get ELEVENLABS_SIP_NUMBER)"; SIP_NUMBER="${SIP_NUMBER:-778}"
LAN_IP="$(env_get PBX_LAN_IP)"; LAN_IP="${LAN_IP:-192.168.0.118}"
LOCAL_NET="$(env_get PBX_LOCAL_NET)"; LOCAL_NET="${LOCAL_NET:-192.168.0.0/24}"
PUBLIC_IP="$(env_get PBX_PUBLIC_IP)"

write_audiosocket() {
  # The caller number rides in the last 12 hex digits of the AudioSocket UUID.
  cat >"$EXT_FILE" <<EOF
; voice-monday ElevenLabs agent route (generated by scripts/pbx-elevenlabs-route.sh)
[voice-monday-el]
exten => $EXT,1,NoOp(voice-monday ElevenLabs agent call from \${CALLERID(num)})
 same => n,Answer()
 same => n,Set(VM_START=\${EPOCH})
 same => n,Set(VM_CID=000000000000\${FILTER(0123456789,\${CALLERID(num)})})
 same => n,AudioSocket(\${UUID():0:24}\${VM_CID:-12},127.0.0.1:$BRIDGE_PORT)
 ; the agent could not start (e.g. no ElevenLabs credits): busy tone, not a silent drop
 same => n,GotoIf(\$[\${EPOCH} - \${VM_START} < 3]?unavailable)
 same => n,Hangup()
 same => n(unavailable),NoOp(voice-monday agent unavailable for \${CALLERID(num)})
 same => n,Congestion(4)
EOF
}

write_sip() {
  [[ -n "$SIP_USER" && -n "$SIP_PASS" ]] \
    || { echo "set ELEVENLABS_SIP_USERNAME and ELEVENLABS_SIP_PASSWORD in .env" >&2; exit 1; }
  [[ "$SIP_USER$SIP_PASS$SIP_NUMBER" =~ ^[A-Za-z0-9_.+-]+$ ]] \
    || { echo "SIP username/password/number: letters, digits, _ . + - only" >&2; exit 1; }
  if [[ -z "$PUBLIC_IP" ]]; then
    PUBLIC_IP="$(curl -fsS -m 5 https://api.ipify.org || true)"
  fi
  [[ "$PUBLIC_IP" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] \
    || { echo "could not determine the office public IP; set PBX_PUBLIC_IP in .env" >&2; exit 1; }

  mkdir -p "$KEYS"
  if [[ ! -f "$KEYS/voice-monday-el.crt" ]]; then
    openssl req -x509 -newkey rsa:2048 -nodes -days 3650 -subj "/CN=$PUBLIC_IP" \
      -keyout "$KEYS/voice-monday-el.key" -out "$KEYS/voice-monday-el.crt" 2>/dev/null
  fi
  chown asterisk:asterisk "$KEYS/voice-monday-el.key" "$KEYS/voice-monday-el.crt"
  chmod 0600 "$KEYS/voice-monday-el.key"

  cat >"$PJSIP_FILE" <<EOF
; voice-monday ElevenLabs agent trunk (generated by scripts/pbx-elevenlabs-route.sh)
[voice-monday-el-tls]
type=transport
protocol=tls
bind=$LAN_IP:5061
method=tlsv1_2
cert_file=$KEYS/voice-monday-el.crt
priv_key_file=$KEYS/voice-monday-el.key
ca_list_file=/etc/ssl/certs/ca-certificates.crt
verify_server=yes
external_signaling_address=$PUBLIC_IP
external_media_address=$PUBLIC_IP
local_net=$LOCAL_NET

[elevenlabs]
type=aor
; ';' starts a comment in Asterisk configs, so the URI parameter must be escaped
contact=sip:sip.rtc.elevenlabs.io:5061\\;transport=tls

[elevenlabs-auth]
type=auth
auth_type=userpass
username=$SIP_USER
password=$SIP_PASS

[elevenlabs]
type=endpoint
transport=voice-monday-el-tls
context=voice-monday-el-inbound
disallow=all
allow=g722,ulaw
aors=elevenlabs
outbound_auth=elevenlabs-auth
direct_media=no
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes
media_encryption=sdes
media_encryption_optimistic=yes
EOF
  chown root:asterisk "$PJSIP_FILE"
  chmod 0640 "$PJSIP_FILE"

  cat >"$EXT_FILE" <<EOF
; voice-monday ElevenLabs agent route (generated by scripts/pbx-elevenlabs-route.sh)
[voice-monday-el]
exten => $EXT,1,NoOp(voice-monday ElevenLabs agent call from \${CALLERID(num)})
 same => n,Dial(PJSIP/$SIP_NUMBER@elevenlabs,60,b(voice-monday-el-headers^s^1))
 same => n,Hangup()

[voice-monday-el-headers]
exten => s,1,Set(PJSIP_HEADER(add,X-CALLER-ID)=\${CALLERID(num)})
 same => n,Return()

[voice-monday-el-inbound]
exten => _X.,1,Hangup()
EOF
}

apply() {
  [[ "$MODE" == "audiosocket" || "$MODE" == "sip" ]] \
    || { echo "AGENT_PBX_MODE must be audiosocket or sip" >&2; exit 1; }
  [[ "$EXT" =~ ^[0-9]+$ && "$BRIDGE_PORT" =~ ^[0-9]+$ ]] \
    || { echo "AGENT_PBX_EXTENSION and EL_BRIDGE_PORT must be digits" >&2; exit 1; }
  if ast "dialplan show $EXT@$CONTEXT" | grep -q "'$EXT' =>" \
      && ! grep -qF "$BEGIN" "$ETC/extensions.conf"; then
    echo "extension $EXT already exists in $CONTEXT; choose another AGENT_PBX_EXTENSION" >&2
    exit 1
  fi

  local backup
  backup="/etc/asterisk.bak-voice-monday-el-$(date +%Y%m%d-%H%M%S)"
  cp -a "$ETC" "$backup"
  echo "backup: $backup ($MODE mode)"

  umask 027
  if [[ "$MODE" == "sip" ]]; then
    write_sip
    if ! grep -qF "$BEGIN" "$ETC/pjsip.conf"; then
      end_nl "$ETC/pjsip.conf"
      printf '%s\n#include pjsip_voice_monday_el.conf\n%s\n' "$BEGIN" "$END" >>"$ETC/pjsip.conf"
    fi
  else
    write_audiosocket
    # switching from sip mode: drop our trunk (the TLS transport fully goes on restart)
    drop_block "$ETC/pjsip.conf"
    rm -f "$PJSIP_FILE"
  fi
  chown root:asterisk "$EXT_FILE"
  chmod 0640 "$EXT_FILE"

  if ! grep -qF "$BEGIN" "$ETC/extensions.conf"; then
    end_nl "$ETC/extensions.conf"
    printf '%s\n[%s](+)\ninclude => voice-monday-el\n#include extensions_voice_monday_el.conf\n%s\n' \
      "$BEGIN" "$CONTEXT" "$END" >>"$ETC/extensions.conf"
  fi

  ast "module reload res_pjsip.so"
  ast "dialplan reload"
  verify
}

revert() {
  drop_block "$ETC/pjsip.conf"
  drop_block "$ETC/extensions.conf"
  rm -f "$PJSIP_FILE" "$EXT_FILE" "$KEYS/voice-monday-el.crt" "$KEYS/voice-monday-el.key"
  ast "dialplan reload"
  ast "module reload res_pjsip.so"
  verify
  echo "reverted (a TLS transport, if one was added, disappears after the next restart)"
}

verify() {
  echo "--- endpoint";  ast "pjsip show endpoint elevenlabs" | grep -E "Endpoint:|Unable" || true
  echo "--- dialplan";  ast "dialplan show $EXT@$CONTEXT" | grep -E "$EXT|Dial|AudioSocket|no existence" || true
}

case "${1:-}" in
  apply) apply ;;
  revert) revert ;;
  verify) verify ;;
  *) echo "usage: sudo $0 apply|revert|verify" >&2; exit 2 ;;
esac
